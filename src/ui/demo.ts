import { addEpgSource, addPlaylist, reloadAll, toast, getState, rematchAndReload, setState } from '../app/state';
import { isNative } from '../app/platform';

/**
 * The demo is clearly labeled and fully removable. Its streams are:
 *  - two short test-pattern HLS streams bundled with the app (generated with ffmpeg's
 *    testsrc/smptebars sources; no third-party content), and
 *  - Mux's public HLS test stream (requires internet).
 * The guide is generated XMLTV for "today" so the EPG grid has real data to show.
 */

function assetUrl(path: string): string {
  // ExoPlayer reads bundled files via asset:/// on Android; the browser uses a normal URL.
  return isNative ? `asset:///www/${path}` : new URL(path, location.href).href;
}

export function demoPlaylist(): string {
  return `#EXTM3U
#EXTINF:-1 tvg-id="demo.pattern" tvg-chno="901" group-title="Demo",DEMO · Test Pattern
${assetUrl('demo/pattern/index.m3u8')}
#EXTINF:-1 tvg-id="demo.bars" tvg-chno="902" group-title="Demo Sports",DEMO · Color Bars
${assetUrl('demo/bars/index.m3u8')}
#EXTINF:-1 tvg-id="demo.mux" tvg-chno="903" group-title="Demo",DEMO · Mux Test Stream (internet)
https://test-streams.mux.dev/x36xhzz/x36xhzz.m3u8
#EXTINF:-1 tvg-chno="904" group-title="Demo",DEMO · Offline Channel (intentionally broken)
http://127.0.0.1:9/demo-offline.m3u8
`;
}

function xmltvTime(t: number) {
  const d = new Date(t);
  const p = (n: number) => String(n).padStart(2, '0');
  return `${d.getUTCFullYear()}${p(d.getUTCMonth() + 1)}${p(d.getUTCDate())}${p(d.getUTCHours())}${p(d.getUTCMinutes())}00 +0000`;
}

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');

export function demoGuide(now = Date.now()): string {
  const start = Math.floor(now / 1800_000) * 1800_000 - 6 * 3600_000;
  const end = start + 36 * 3600_000;
  const chans = [
    { id: 'demo.pattern', name: 'DEMO · Test Pattern', shows: ['Demo Morning Show', 'Demo Test Card Hour', 'Demo Documentary: How Test Patterns Work', 'Demo Late Movie (crosses midnight)'] },
    { id: 'demo.bars', name: 'DEMO · Color Bars', shows: ['DEMO GAME (not a real broadcast): New York Giants at Philadelphia Eagles', 'Demo Sports Highlights', 'DEMO GAME (not a real broadcast): Lakers vs Celtics', 'Demo Music Hour'] },
    { id: 'demo.mux', name: 'DEMO · Mux Test Stream', shows: ['Demo Feature Presentation', 'Demo Behind the Scenes', 'Demo Feature Presentation (Repeat)'] },
  ];
  const parts = ['<?xml version="1.0" encoding="UTF-8"?>', '<tv generator-info-name="LTTV demo">'];
  for (const c of chans) parts.push(`<channel id="${c.id}"><display-name>${esc(c.name)}</display-name></channel>`);
  chans.forEach((c, ci) => {
    let t = start;
    let i = ci;
    while (t < end) {
      const lenMin = [30, 60, 90, 120][(i * 7 + ci) % 4];
      const title = c.shows[i % c.shows.length];
      const stop = t + lenMin * 60_000;
      parts.push(
        `<programme start="${xmltvTime(t)}" stop="${xmltvTime(stop)}" channel="${c.id}"><title>${esc(title)}</title>` +
          `<desc>Demo guide entry generated by LTTV for testing the program guide. Not a real broadcast.</desc>` +
          `<category>${title.startsWith('DEMO GAME') ? 'Sports' : 'Demo'}</category><episode-num system="onscreen">S1E${(i % 12) + 1}</episode-num></programme>`,
      );
      t = stop;
      i++;
    }
  });
  parts.push('</tv>');
  return parts.join('\n');
}

export async function loadDemo() {
  if (getState().playlists.some((p) => p.name.startsWith('LTTV Demo'))) {
    toast('The demo is already loaded.');
    return;
  }
  try {
    const guideFile = new File([demoGuide()], 'lttv-demo-guide.xml', { type: 'text/xml' });
    const { source } = await addEpgSource({ name: 'LTTV Demo Guide', input: { file: guideFile } });
    const plFile = new File([demoPlaylist()], 'lttv-demo.m3u', { type: 'audio/x-mpegurl' });
    await addPlaylist({ name: 'LTTV Demo Channels', input: { file: plFile }, epgIds: [source.id] });
    await rematchAndReload(false);
    await reloadAll();
    setState({ screen: 'home' });
    toast('Demo loaded. Remove it anytime in Sources.', 'success');
  } catch (e) {
    toast('Could not load the demo: ' + (e as Error).message, 'error', 8000);
  }
}
